-- 原生撤销重发只持久化安全控制面数据；禁止加入 prompt、回答、附件正文和工具输入输出。
create table run_resends (
    id bigint generated by default as identity primary key,
    resend_id varchar(128) not null unique,
    session_id varchar(128) not null,
    owner_user_id varchar(128) not null,
    source_run_id varchar(128) not null,
    replacement_run_id varchar(128) not null,
    source_remote_message_id varchar(128) not null,
    replacement_remote_message_id varchar(128) not null,
    trigger_type varchar(32) not null,
    total_attempt integer not null,
    automatic_attempt integer not null,
    automatic_limit integer not null,
    status varchar(32) not null,
    execute_at timestamp not null,
    target_linux_server_id varchar(128) not null,
    lease_token varchar(128),
    lease_until timestamp,
    client_request_id varchar(128) not null,
    trace_id varchar(128) not null,
    safe_error_message varchar(512),
    created_at timestamp not null,
    updated_at timestamp not null,
    constraint fk_run_resends_session foreign key (session_id) references sessions(session_id),
    constraint fk_run_resends_owner foreign key (owner_user_id) references users(user_id),
    constraint fk_run_resends_source_run foreign key (source_run_id) references runs(run_id),
    constraint fk_run_resends_replacement_run foreign key (replacement_run_id) references runs(run_id),
    constraint uq_run_resends_source_run unique (source_run_id),
    constraint uq_run_resends_replacement_run unique (replacement_run_id),
    constraint uq_run_resends_owner_request unique (owner_user_id, client_request_id),
    constraint ck_run_resends_attempts check (
        total_attempt >= 1 and automatic_attempt >= 0
        and automatic_attempt <= automatic_limit and automatic_limit >= 1
    ),
    constraint ck_run_resends_trigger check (trigger_type in ('MANUAL','AUTOMATIC')),
    constraint ck_run_resends_status check (
        status in ('WAITING','REVERTING','REVERTED','DISPATCHED','FAILED','CANCELLED')
    ),
    constraint ck_run_resends_lease_pair check (
        (lease_token is null and lease_until is null)
        or (lease_token is not null and lease_until is not null)
    )
);

create table run_resend_session_locks (
    session_id varchar(128) primary key,
    resend_id varchar(128) not null unique,
    owner_user_id varchar(128) not null,
    created_at timestamp not null,
    constraint fk_run_resend_locks_session foreign key (session_id) references sessions(session_id),
    constraint fk_run_resend_locks_resend foreign key (resend_id) references run_resends(resend_id),
    constraint fk_run_resend_locks_owner foreign key (owner_user_id) references users(user_id)
);

create index idx_run_resends_due on run_resends(status, execute_at, created_at);
create index idx_run_resends_session on run_resends(session_id, created_at);
create index idx_run_resends_chain on run_resends(source_run_id, replacement_run_id);
