-- 内部模型代理调用可观测性：明细、小时聚合、探活状态三张表。
-- 只存结构化字段，禁止写入请求/响应正文、错误文本、Token 或密钥。
-- 保留期由 XXL 任务 internal-model-observability-retention 执行清理：明细 30 天、聚合 180 天。

create table internal_model_call_records (
    id bigint generated by default as identity primary key,
    provider_id varchar(128) not null,
    model varchar(255),
    endpoint varchar(64) not null,
    source varchar(16) not null,
    outcome varchar(48) not null,
    http_status int,
    error_class varchar(255),
    streaming boolean not null default false,
    duration_ms bigint not null,
    first_byte_ms bigint,
    trace_id varchar(128) not null,
    ucid varchar(128),
    started_at timestamp not null
);

create index idx_imcr_provider_time on internal_model_call_records(provider_id, started_at desc);
create index idx_imcr_outcome_time on internal_model_call_records(outcome, started_at desc);
create index idx_imcr_retention on internal_model_call_records(started_at);

create table internal_model_call_stats_hourly (
    stat_hour timestamp not null,
    provider_id varchar(128) not null,
    model varchar(255) not null,
    endpoint varchar(64) not null,
    source varchar(16) not null,
    outcome varchar(48) not null,
    request_count bigint not null default 0,
    duration_ms_sum bigint not null default 0,
    duration_ms_max bigint not null default 0,
    updated_at timestamp not null,
    primary key (stat_hour, provider_id, model, endpoint, source, outcome)
);

create index idx_imcsh_provider_hour on internal_model_call_stats_hourly(provider_id, stat_hour desc);

create table internal_model_probe_status (
    provider_id varchar(128) primary key,
    last_outcome varchar(48) not null,
    last_http_status int,
    last_error_class varchar(255),
    last_duration_ms bigint,
    last_probed_at timestamp not null,
    last_success_at timestamp,
    consecutive_failures int not null default 0,
    trace_id varchar(128) not null,
    updated_at timestamp not null
);

