-- QA 长期记忆治理控制面。完整记忆正文、向量和历史只保存在独立 Mem0；本迁移禁止保存聊天原文。
create table qa_memories (
    id bigint generated by default as identity primary key,
    memory_id varchar(128) not null unique,
    mem0_memory_id varchar(128),
    scope varchar(32) not null,
    owner_user_id varchar(128),
    application_id varchar(128),
    status varchar(32) not null,
    source varchar(32) not null,
    task_types_csv varchar(1024) not null,
    display_summary varchar(500) not null,
    confidence decimal(6, 5) not null default 0,
    distinct_session_count integer not null default 0,
    distinct_user_count integer not null default 0,
    first_observed_at timestamp with time zone not null,
    last_observed_at timestamp with time zone not null,
    confirmed_at timestamp with time zone,
    superseded_by_memory_id varchar(128),
    created_by_user_id varchar(128) not null,
    version bigint not null default 0,
    vector_sync_status varchar(32) not null default 'PENDING',
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    constraint fk_qa_memories_application foreign key (application_id) references applications(app_id),
    constraint fk_qa_memories_superseded_by foreign key (superseded_by_memory_id) references qa_memories(memory_id),
    constraint ck_qa_memories_scope_owner check (
        (scope = 'PERSONAL_GLOBAL' and owner_user_id is not null and application_id is null)
        or (scope = 'PERSONAL_APPLICATION' and owner_user_id is not null and application_id is not null)
        or (scope = 'TEAM_APPLICATION' and owner_user_id is null and application_id is not null)
    ),
    constraint ck_qa_memories_confidence check (confidence >= 0 and confidence <= 1),
    constraint ck_qa_memories_counts check (
        distinct_session_count >= 0 and distinct_user_count >= 0 and version >= 0
    )
);

create table qa_memory_evidence (
    id bigint generated by default as identity primary key,
    evidence_id varchar(128) not null unique,
    memory_id varchar(128) not null,
    run_id varchar(128) not null,
    session_id varchar(128) not null,
    observed_user_id varchar(128) not null,
    source varchar(32) not null,
    evidence_summary varchar(200) not null,
    observed_at timestamp with time zone not null,
    constraint fk_qa_memory_evidence_memory foreign key (memory_id) references qa_memories(memory_id) on delete cascade,
    constraint fk_qa_memory_evidence_run foreign key (run_id) references runs(run_id),
    constraint fk_qa_memory_evidence_session foreign key (session_id) references sessions(session_id),
    constraint uk_qa_memory_evidence_memory_run unique (memory_id, run_id)
);

create table qa_memory_reviews (
    id bigint generated by default as identity primary key,
    review_id varchar(128) not null unique,
    memory_id varchar(128) not null,
    application_id varchar(128) not null,
    submitted_by_user_id varchar(128) not null,
    reviewed_by_user_id varchar(128),
    decision varchar(32) not null,
    comment varchar(1000),
    submitted_at timestamp with time zone not null,
    reviewed_at timestamp with time zone,
    constraint fk_qa_memory_reviews_memory foreign key (memory_id) references qa_memories(memory_id) on delete cascade,
    constraint fk_qa_memory_reviews_application foreign key (application_id) references applications(app_id)
);

create table qa_memory_learning_outbox (
    id bigint generated by default as identity primary key,
    job_id varchar(128) not null unique,
    run_id varchar(128) not null unique,
    session_id varchar(128) not null,
    workspace_id varchar(128) not null,
    user_id varchar(128) not null,
    application_id varchar(128),
    agent_id varchar(128) not null,
    selected_model_id varchar(255),
    status varchar(32) not null,
    attempts integer not null default 0,
    available_at timestamp with time zone not null,
    claimed_by varchar(128),
    lease_until timestamp with time zone,
    last_error_code varchar(128),
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    constraint fk_qa_memory_outbox_run foreign key (run_id) references runs(run_id),
    constraint fk_qa_memory_outbox_session foreign key (session_id) references sessions(session_id),
    constraint fk_qa_memory_outbox_workspace foreign key (workspace_id) references workspaces(workspace_id),
    constraint fk_qa_memory_outbox_application foreign key (application_id) references applications(app_id),
    constraint ck_qa_memory_outbox_attempts check (attempts >= 0)
);

create table qa_memory_run_usage (
    id bigint generated by default as identity primary key,
    run_id varchar(128) not null,
    memory_id varchar(128) not null,
    user_id varchar(128) not null,
    application_id varchar(128),
    scope varchar(32) not null,
    rank_index integer not null,
    token_count integer not null,
    injected_at timestamp with time zone not null,
    constraint fk_qa_memory_usage_run foreign key (run_id) references runs(run_id),
    constraint fk_qa_memory_usage_memory foreign key (memory_id) references qa_memories(memory_id),
    constraint fk_qa_memory_usage_application foreign key (application_id) references applications(app_id),
    constraint uk_qa_memory_usage_run_memory unique (run_id, memory_id),
    constraint ck_qa_memory_usage_rank check (rank_index > 0 and token_count >= 0)
);

create table qa_memory_whitelist (
    id bigint generated by default as identity primary key,
    user_id varchar(128) not null unique,
    enabled boolean not null default true,
    updated_by_user_id varchar(128) not null,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null
);

create table qa_memory_skill_proposals (
    id bigint generated by default as identity primary key,
    proposal_id varchar(128) not null unique,
    memory_id varchar(128) not null,
    application_id varchar(128) not null,
    title varchar(255) not null,
    skill_md_draft text not null,
    status varchar(32) not null,
    created_by_user_id varchar(128) not null,
    reviewed_by_user_id varchar(128),
    published_asset_id varchar(128),
    version bigint not null default 0,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    constraint fk_qa_memory_skill_memory foreign key (memory_id) references qa_memories(memory_id),
    constraint fk_qa_memory_skill_application foreign key (application_id) references applications(app_id),
    constraint ck_qa_memory_skill_version check (version >= 0)
);

create table qa_memory_settings (
    setting_key varchar(64) primary key,
    primary_chat_model_id varchar(255),
    current_run_model_fallback_enabled boolean not null default true,
    version bigint not null default 0,
    updated_by_user_id varchar(128) not null,
    updated_at timestamp with time zone not null,
    constraint ck_qa_memory_settings_version check (version >= 0)
);

insert into qa_memory_settings(
    setting_key, primary_chat_model_id, current_run_model_fallback_enabled,
    version, updated_by_user_id, updated_at
) values ('DEFAULT', null, true, 0, 'system', current_timestamp);

create index idx_qa_memories_personal on qa_memories(owner_user_id, status, application_id, updated_at desc);
create index idx_qa_memories_team on qa_memories(application_id, status, updated_at desc);
create index idx_qa_memory_evidence_memory on qa_memory_evidence(memory_id, observed_at desc);
create index idx_qa_memory_reviews_memory on qa_memory_reviews(memory_id, submitted_at desc);
create index idx_qa_memory_outbox_claim on qa_memory_learning_outbox(status, available_at, lease_until);
create index idx_qa_memory_usage_user_run on qa_memory_run_usage(user_id, run_id, rank_index);
create index idx_qa_memory_skill_app on qa_memory_skill_proposals(application_id, status, updated_at desc);

