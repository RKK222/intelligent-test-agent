-- 平台协作分享只保存身份、授权和安全审计元数据，不保存消息/文件正文、明文路径、Token 或终端输入。
create table session_shares (
    id bigint generated by default as identity primary key,
    share_id varchar(68) not null,
    session_id varchar(128) not null,
    workspace_id varchar(128) not null,
    owner_user_id varchar(128) not null,
    status varchar(32) not null,
    expires_at timestamp not null,
    lock_version bigint not null default 0,
    trace_id varchar(128) not null,
    created_at timestamp not null,
    updated_at timestamp not null,
    revoked_at timestamp,
    constraint uk_session_shares_share_id unique (share_id),
    constraint uk_session_shares_session_id unique (session_id),
    constraint fk_session_shares_session foreign key (session_id) references sessions(session_id),
    constraint fk_session_shares_workspace foreign key (workspace_id) references workspaces(workspace_id),
    constraint fk_session_shares_owner foreign key (owner_user_id) references users(user_id),
    constraint ck_session_shares_status check (status in ('ACTIVE', 'REVOKED')),
    constraint ck_session_shares_version check (lock_version >= 0),
    constraint ck_session_shares_revoked_at check (
        (status = 'ACTIVE' and revoked_at is null)
        or (status = 'REVOKED' and revoked_at is not null)
    )
);

create table session_share_memberships (
    id bigint generated by default as identity primary key,
    share_id varchar(68) not null,
    user_id varchar(128) not null,
    unified_auth_id varchar(255) not null,
    username varchar(128) not null,
    can_chat boolean not null,
    status varchar(32) not null,
    shared_at timestamp not null,
    updated_at timestamp not null,
    removed_at timestamp,
    constraint uk_session_share_memberships_user unique (share_id, user_id),
    constraint fk_session_share_memberships_share foreign key (share_id)
        references session_shares(share_id) on delete cascade,
    constraint fk_session_share_memberships_user foreign key (user_id) references users(user_id),
    constraint ck_session_share_memberships_status check (status in ('ACTIVE', 'REMOVED')),
    constraint ck_session_share_memberships_removed_at check (
        (status = 'ACTIVE' and removed_at is null)
        or (status = 'REMOVED' and removed_at is not null)
    )
);

create table session_share_audit_events (
    id bigint generated by default as identity primary key,
    audit_event_id varchar(128) not null unique,
    share_id varchar(68) not null,
    session_id varchar(128) not null,
    workspace_id varchar(128) not null,
    actor_user_id varchar(128) not null,
    execution_owner_user_id varchar(128) not null,
    action varchar(64) not null,
    resource_type varchar(64) not null,
    resource_id varchar(128),
    resource_path_sha256 char(64),
    outcome varchar(32) not null,
    error_code varchar(64),
    trace_id varchar(128) not null,
    occurred_at timestamp not null,
    constraint fk_session_share_audit_share foreign key (share_id) references session_shares(share_id),
    constraint ck_session_share_audit_outcome check (outcome in ('SUCCESS', 'DENIED', 'FAILED')),
    constraint ck_session_share_audit_path_digest check (
        resource_path_sha256 is null or char_length(resource_path_sha256) = 64
    )
);

create index idx_session_share_memberships_user_status
    on session_share_memberships(user_id, status, updated_at);
create index idx_session_shares_owner_updated
    on session_shares(owner_user_id, updated_at);
create index idx_session_share_audit_occurred
    on session_share_audit_events(occurred_at, share_id);
create index idx_session_share_audit_actor
    on session_share_audit_events(actor_user_id, occurred_at);

