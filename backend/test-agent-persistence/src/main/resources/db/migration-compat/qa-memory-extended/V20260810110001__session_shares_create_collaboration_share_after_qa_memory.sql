comment on column session_share_memberships.can_chat is '是否允许在分享范围内代所属人执行写操作';
comment on table session_share_audit_events is '分享范围安全审计；路径仅允许保存 SHA-256 摘要';
comment on column session_share_audit_events.resource_path_sha256 is '文件路径 SHA-256；禁止写入明文路径';
