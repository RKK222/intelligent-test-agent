create table support_access_grants (
    id bigint generated by default as identity primary key,
    grant_id varchar(128) not null unique,
    actor_user_id varchar(128),
    actor_username varchar(128) not null,
    incident_id varchar(128) not null,
    reason varchar(1000) not null,
    session_digest char(64) not null,
    issued_at timestamp not null,
    expires_at timestamp not null,
    revoked_at timestamp,
    revoke_reason varchar(255),
    trace_id varchar(128) not null,
    constraint fk_support_access_grant_actor foreign key (actor_user_id) references users(user_id) on delete set null,
    constraint ck_support_access_grant_expiry check (expires_at > issued_at)
);

create table support_access_audit_events (
    id bigint generated by default as identity primary key,
    event_id varchar(128) not null unique,
    grant_id varchar(128),
    actor_user_id varchar(128),
    actor_username varchar(128) not null,
    target_user_id varchar(128),
    target_username varchar(128),
    incident_id varchar(128),
    reason varchar(1000),
    action varchar(64) not null,
    resource_type varchar(64) not null,
    resource_id varchar(255),
    path_digest char(64),
    outcome varchar(32) not null,
    error_code varchar(64),
    trace_id varchar(128) not null,
    ip_address varchar(64),
    user_agent_digest char(64),
    occurred_at timestamp not null,
    constraint fk_support_access_audit_grant foreign key (grant_id) references support_access_grants(grant_id) on delete set null,
    constraint fk_support_access_audit_actor foreign key (actor_user_id) references users(user_id) on delete set null,
    constraint fk_support_access_audit_target foreign key (target_user_id) references users(user_id) on delete set null
);

create index idx_support_access_grants_actor_time
    on support_access_grants(actor_user_id, issued_at desc);
create index idx_support_access_grants_session_time
    on support_access_grants(session_digest, issued_at desc);
create index idx_support_access_grants_expiry
    on support_access_grants(expires_at, revoked_at);
create index idx_support_access_audit_actor_time
    on support_access_audit_events(actor_user_id, occurred_at desc);
create index idx_support_access_audit_target_time
    on support_access_audit_events(target_user_id, occurred_at desc);
create index idx_support_access_audit_grant_time
    on support_access_audit_events(grant_id, occurred_at desc);
create index idx_support_access_audit_incident_time
    on support_access_audit_events(incident_id, occurred_at desc);
create index idx_support_access_audit_retention
    on support_access_audit_events(occurred_at);

