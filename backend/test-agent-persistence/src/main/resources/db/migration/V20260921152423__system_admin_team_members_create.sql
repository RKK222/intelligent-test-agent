create table system_admin_team_members (
    id bigint generated by default as identity primary key,
    owner_user_id varchar(128) not null,
    member_user_id varchar(128) not null,
    added_by_user_id varchar(128) not null,
    created_at timestamp not null,
    updated_at timestamp not null,
    deleted_at timestamp,
    constraint fk_system_admin_team_owner foreign key (owner_user_id) references users(user_id),
    constraint fk_system_admin_team_member foreign key (member_user_id) references users(user_id),
    constraint fk_system_admin_team_added_by foreign key (added_by_user_id) references users(user_id),
    constraint uk_system_admin_team_owner_member unique (owner_user_id, member_user_id),
    constraint ck_system_admin_team_not_self check (owner_user_id <> member_user_id)
);

create index idx_system_admin_team_owner_active
    on system_admin_team_members(owner_user_id, deleted_at, updated_at desc);
create index idx_system_admin_team_member_active
    on system_admin_team_members(member_user_id, deleted_at);

create table team_workspace_export_jobs (
    id bigint generated by default as identity primary key,
    export_id varchar(128) not null unique,
    actor_user_id varchar(128),
    owner_user_id varchar(128),
    scope_mode varchar(32) not null,
    version_id varchar(128) not null,
    coordinator_linux_server_id varchar(128) not null,
    status varchar(32) not null,
    total_items integer not null default 0,
    completed_items integer not null default 0,
    succeeded_items integer not null default 0,
    failed_items integer not null default 0,
    file_count integer not null default 0,
    uncompressed_bytes bigint not null default 0,
    archive_bytes bigint,
    archive_sha256 char(64),
    artifact_file_name varchar(255),
    error_code varchar(64),
    error_message varchar(1000),
    lease_owner varchar(128),
    lease_token varchar(128),
    lease_expires_at timestamp,
    created_at timestamp not null,
    started_at timestamp,
    completed_at timestamp,
    expires_at timestamp not null,
    cancelled_at timestamp,
    constraint fk_team_workspace_export_actor foreign key (actor_user_id) references users(user_id) on delete set null,
    constraint fk_team_workspace_export_owner foreign key (owner_user_id) references users(user_id) on delete set null,
    constraint fk_team_workspace_export_version foreign key (version_id) references application_workspace_versions(version_id),
    constraint ck_team_workspace_export_scope check (scope_mode in ('MY_TEAM', 'SYSTEM_ADMIN_TEAM', 'GLOBAL')),
    constraint ck_team_workspace_export_status check (status in (
        'QUEUED', 'RUNNING', 'READY', 'PARTIAL_READY', 'FAILED', 'CANCELLED', 'EXPIRED'
    )),
    constraint ck_team_workspace_export_non_negative check (
        total_items >= 0 and completed_items >= 0 and succeeded_items >= 0
        and failed_items >= 0 and file_count >= 0 and uncompressed_bytes >= 0
    )
);

create index idx_team_workspace_export_actor_time
    on team_workspace_export_jobs(actor_user_id, created_at desc);
create index idx_team_workspace_export_status_lease
    on team_workspace_export_jobs(status, lease_expires_at, created_at);
create index idx_team_workspace_export_expiry
    on team_workspace_export_jobs(expires_at, status);

create table team_workspace_export_items (
    id bigint generated by default as identity primary key,
    export_item_id varchar(128) not null unique,
    export_id varchar(128) not null,
    user_id varchar(128) not null,
    personal_workspace_id varchar(128),
    source_linux_server_id varchar(128),
    status varchar(32) not null,
    file_count integer not null default 0,
    uncompressed_bytes bigint not null default 0,
    shard_bytes bigint,
    shard_sha256 char(64),
    error_code varchar(64),
    error_message varchar(1000),
    lease_owner varchar(128),
    lease_token varchar(128),
    lease_expires_at timestamp,
    created_at timestamp not null,
    updated_at timestamp not null,
    constraint fk_team_workspace_export_item_job foreign key (export_id)
        references team_workspace_export_jobs(export_id) on delete cascade,
    constraint fk_team_workspace_export_item_user foreign key (user_id) references users(user_id),
    -- 导出明细是历史快照，个人 worktree 清理后仍需保留标识和失败清单；
    -- 同时兼容尚未部署个人工作区表的既有 Flyway 历史，因此不建立物理外键。
    constraint uk_team_workspace_export_item unique (export_id, user_id, personal_workspace_id),
    constraint ck_team_workspace_export_item_status check (status in (
        'QUEUED', 'RUNNING', 'SUCCEEDED', 'FAILED', 'NO_WORKTREE', 'CANCELLED'
    )),
    constraint ck_team_workspace_export_item_non_negative check (file_count >= 0 and uncompressed_bytes >= 0)
);

create index idx_team_workspace_export_item_job_status
    on team_workspace_export_items(export_id, status, id);
create index idx_team_workspace_export_item_lease
    on team_workspace_export_items(status, lease_expires_at, id);

