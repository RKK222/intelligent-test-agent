create table analytics_event_outbox (
    id bigint generated by default as identity primary key,
    event_id varchar(256) not null,
    event_version bigint not null,
    source_type varchar(32) not null,
    aggregate_id varchar(256) not null,
    occurred_at timestamp with time zone not null,
    payload_json text not null,
    attempt_count integer not null default 0,
    available_at timestamp with time zone not null,
    published_at timestamp with time zone,
    last_error varchar(500),
    created_at timestamp with time zone not null,
    constraint uk_analytics_event_outbox_event unique (event_id, event_version)
);

create index idx_analytics_event_outbox_pending
    on analytics_event_outbox(published_at, available_at, id);

create table analytics_redis_outbox_checkpoints (
    run_id varchar(128) primary key,
    last_stream_id varchar(64) not null,
    updated_at timestamp with time zone not null
);

create table analytics_clickhouse_cutovers (
    cutover_id varchar(64) primary key,
    status varchar(32) not null,
    source_row_count bigint not null default 0,
    target_row_count bigint not null default 0,
    coverage_start timestamp with time zone,
    coverage_end timestamp with time zone,
    attribution_mode varchar(32) not null default 'CURRENT_ORG_BACKFILL',
    verified_at timestamp with time zone,
    updated_at timestamp with time zone not null
);

