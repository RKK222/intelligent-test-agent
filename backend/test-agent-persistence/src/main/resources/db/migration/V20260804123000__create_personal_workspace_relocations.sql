create table personal_workspace_relocations (
    id bigint generated by default as identity primary key,
    relocation_id varchar(128) not null unique,
    personal_workspace_id varchar(128) not null unique,
    app_workspace_version_id varchar(128) not null,
    user_id varchar(128) not null,
    runtime_workspace_id varchar(128) not null,
    source_linux_server_id varchar(128) not null,
    target_linux_server_id varchar(128) not null,
    branch varchar(255) not null,
    source_repo_root_path text not null,
    source_workspace_root_path text not null,
    status varchar(32) not null,
    attempt_count integer not null default 0,
    lease_owner varchar(255),
    lease_until timestamp,
    next_retry_at timestamp not null,
    snapshot_sha256 varchar(64),
    archive_size_bytes bigint,
    safe_error_code varchar(64),
    safe_error_message varchar(512),
    trace_id varchar(128) not null,
    target_applied_at timestamp,
    completed_at timestamp,
    created_at timestamp not null,
    updated_at timestamp not null,
    constraint fk_personal_workspace_relocations_personal
        foreign key (personal_workspace_id) references personal_workspaces(personal_workspace_id),
    constraint fk_personal_workspace_relocations_version
        foreign key (app_workspace_version_id) references application_workspace_versions(version_id),
    constraint fk_personal_workspace_relocations_user
        foreign key (user_id) references users(user_id),
    constraint fk_personal_workspace_relocations_runtime
        foreign key (runtime_workspace_id) references workspaces(workspace_id),
    constraint chk_personal_workspace_relocations_servers
        check (source_linux_server_id <> target_linux_server_id),
    constraint chk_personal_workspace_relocations_attempt
        check (attempt_count >= 0),
    constraint chk_personal_workspace_relocations_archive_size
        check (archive_size_bytes is null or archive_size_bytes >= 0),
    constraint chk_personal_workspace_relocations_status
        check (status in (
            'DISCOVERED', 'EXPORTING', 'TRANSFERRING', 'APPLYING',
            'CLEANUP_PENDING', 'RETRY_WAIT', 'SUCCEEDED', 'CANCELLED'
        ))
);

create index idx_personal_workspace_relocations_claim
    on personal_workspace_relocations(source_linux_server_id, status, next_retry_at, lease_until, updated_at);

comment on table personal_workspace_relocations is
    '个人工作区与用户 Agent 跨服务器错配的两阶段搬迁状态；目标恢复校验成功后才切换 Workspace 归属。';
comment on column personal_workspace_relocations.source_repo_root_path is
    '搬迁发现时的源端个人仓库逻辑路径，仅供原服务器在目标切换成功后清理旧 worktree。';
comment on column personal_workspace_relocations.snapshot_sha256 is
    '源端 Git 工作态快照归档的 SHA-256，用于 WebSocket 传输和目标恢复完整性校验。';
comment on column personal_workspace_relocations.target_applied_at is
    '目标端恢复并在同一事务中完成 Workspace 与个人工作区数据库切换的时间。';
