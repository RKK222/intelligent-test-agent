/** 验证团队 migration、MyBatis 软删除恢复和 TEAM_OVERSIGHT 审计类型。 */
class SystemAdminTeamRepositoryIntegrationTest {

    private static final Instant NOW = Instant.parse("2026-09-21T08:00:00Z");
    private SingleConnectionDataSource dataSource;
    private MyBatisSystemAdminTeamRepository repository;
    private MyBatisTeamWorkspaceExportRepository exportRepository;
    private JdbcClient jdbc;

    @BeforeEach
    void setUp() throws Exception {
        dataSource = new SingleConnectionDataSource(
                "jdbc:h2:mem:testagent_team_%s;MODE=PostgreSQL;DATABASE_TO_UPPER=false"
                        .formatted(UUID.randomUUID().toString().replace("-", "")),
                "sa", "", true);
        new ResourceDatabasePopulator(new ByteArrayResource("""
                create table users (
                    id bigint generated by default as identity primary key,
                    user_id varchar(128) not null unique,
                    unified_auth_id varchar(128) not null unique,
                    username varchar(128) not null,
                    password_hash varchar(255) not null,
                    organization varchar(255), rd_department varchar(255), department varchar(255),
                    status varchar(32) not null, created_at timestamp not null, updated_at timestamp not null
                );
                create table application_workspace_versions (
                    version_id varchar(128) primary key
                );
                create table personal_workspaces (
                    personal_workspace_id varchar(128) primary key
                );
                create table support_access_audit_events (
                    id bigint generated by default as identity primary key,
                    event_id varchar(128) not null unique, grant_id varchar(128),
                    actor_user_id varchar(128), actor_username varchar(128) not null,
                    target_user_id varchar(128), target_username varchar(128), incident_id varchar(128),
                    reason varchar(1000), action varchar(64) not null, resource_type varchar(64) not null,
                    resource_id varchar(255), path_digest char(64), outcome varchar(32) not null,
                    error_code varchar(64), trace_id varchar(128) not null, ip_address varchar(64),
                    user_agent_digest char(64), occurred_at timestamp not null
                );
                """.getBytes(StandardCharsets.UTF_8))).execute(dataSource);
        new ResourceDatabasePopulator(new ClassPathResource(
                "db/migration/V20260921152423__system_admin_team_members_create.sql")).execute(dataSource);
        jdbc = JdbcClient.create(dataSource);
        jdbc.sql("""
                insert into users(user_id, unified_auth_id, username, password_hash, status, created_at, updated_at)
                values ('owner', 'owner-auth', 'owner-name', 'hash', 'ACTIVE', :now, :now),
                       ('member', 'member-auth', 'member-name', 'hash', 'ACTIVE', :now, :now)
                """).param("now", NOW).update();
        Repositories repositories = repositories();
        repository = repositories.teams();
        exportRepository = repositories.exports();
    }

    @AfterEach
    void tearDown() {
        dataSource.destroy();
    }

    @Test
    void softDeletesRestoresAndKeepsOriginalCreationTime() {
        UserId owner = new UserId("owner");
        UserId member = new UserId("member");
        repository.save(new SystemAdminTeamMember(owner, member, owner, NOW, NOW, null));
        assertThat(repository.findMembers(owner, null, new PageRequest(1, 20)).total()).isOne();

        repository.deactivate(owner, member, NOW.plusSeconds(60));
        assertThat(repository.isActiveMember(owner, member)).isFalse();
        assertThat(repository.find(owner, member)).get().extracting(SystemAdminTeamMember::deletedAt).isNotNull();

        repository.save(new SystemAdminTeamMember(owner, member, owner, NOW, NOW.plusSeconds(120), null));
        assertThat(repository.isActiveMember(owner, member)).isTrue();
        assertThat(repository.find(owner, member)).get().satisfies(value -> {
            assertThat(value.createdAt()).isEqualTo(NOW);
            assertThat(value.deletedAt()).isNull();
        });
    }

    @Test
    void writesTeamOversightAuditWithoutPlaintextPath() {
        repository.append(new TeamOversightAuditEvent(
                "toe_test", "owner", "owner-name", "member", "member-name",
                "WORKSPACE_READ", "WORKSPACE_FILE", "pw1", "a".repeat(64),
                "SUCCESS", null, "trace-team", "127.0.0.1", "b".repeat(64), NOW));

        assertThat(jdbc.sql("select access_kind from support_access_audit_events where event_id='toe_test'")
                .query(String.class).single()).isEqualTo("TEAM_OVERSIGHT");
        assertThat(jdbc.sql("select path_digest from support_access_audit_events where event_id='toe_test'")
                .query(String.class).single()).isEqualTo("a".repeat(64));
    }

    @Test
    void claimsExportItemOnlyOnceAndPersistsWorkerLease() {
        jdbc.sql("insert into application_workspace_versions(version_id) values ('version-team')").update();
        jdbc.sql("""
                insert into team_workspace_export_jobs(
                    export_id, actor_user_id, owner_user_id, scope_mode, version_id,
                    coordinator_linux_server_id, status, expires_at, created_at)
                values ('export-team', 'owner', 'owner', 'MY_TEAM', 'version-team',
                        'server-a', 'QUEUED', :expiresAt, :now)
                """).param("expiresAt", NOW.plusSeconds(7200)).param("now", NOW).update();
        jdbc.sql("""
                insert into team_workspace_export_items(
                    export_item_id, export_id, user_id, status, created_at, updated_at)
                values ('item-team', 'export-team', 'member', 'QUEUED', :now, :now)
                """).param("now", NOW).update();

        assertThat(exportRepository.claimItem(
                "item-team", "server-a", "lease-a", NOW, NOW.plusSeconds(600))).isTrue();
        assertThat(exportRepository.claimItem(
                "item-team", "server-b", "lease-b", NOW, NOW.plusSeconds(600))).isFalse();
        assertThat(jdbc.sql("select lease_token from team_workspace_export_items where export_item_id='item-team'")
                .query(String.class).single()).isEqualTo("lease-a");
        assertThat(exportRepository.findActiveByTeamMember("owner", "member"))
                .extracting(com.enterprise.testagent.domain.team.TeamWorkspaceExportJob::exportId)
                .containsExactly("export-team");

        jdbc.sql("update team_workspace_export_jobs set status='CANCELLED' where export_id='export-team'")
                .update();
        assertThat(exportRepository.findExpiredReady("server-b", NOW, 10)).isEmpty();
        assertThat(exportRepository.findExpiredReady("server-a", NOW, 10))
                .extracting(com.enterprise.testagent.domain.team.TeamWorkspaceExportJob::exportId)
                .containsExactly("export-team");
    }

    private Repositories repositories() throws Exception {
        VendorDatabaseIdProvider provider = new VendorDatabaseIdProvider();
        Properties ids = new Properties();
        ids.setProperty("H2", "h2");
        provider.setProperties(ids);
        SqlSessionFactoryBean factoryBean = new SqlSessionFactoryBean();
        factoryBean.setDataSource(dataSource);
        factoryBean.setDatabaseIdProvider(provider);
        factoryBean.setMapperLocations(
                new ClassPathResource("mybatis/SystemAdminTeamMapper.xml"),
                new ClassPathResource("mybatis/TeamWorkspaceExportMapper.xml"));
        SqlSessionFactory factory = factoryBean.getObject();
        SqlSessionTemplate template = new SqlSessionTemplate(factory);
        return new Repositories(
                new MyBatisSystemAdminTeamRepository(template.getMapper(SystemAdminTeamMapper.class)),
                new MyBatisTeamWorkspaceExportRepository(template.getMapper(TeamWorkspaceExportMapper.class)));
    }

    private record Repositories(
            MyBatisSystemAdminTeamRepository teams,
            MyBatisTeamWorkspaceExportRepository exports) {
    }
}
