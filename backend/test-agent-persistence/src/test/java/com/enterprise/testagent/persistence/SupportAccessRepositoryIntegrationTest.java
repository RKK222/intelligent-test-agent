package com.enterprise.testagent.persistence;

import static org.assertj.core.api.Assertions.assertThat;

import com.enterprise.testagent.common.pagination.PageRequest;
import com.enterprise.testagent.domain.supportaccess.SupportAccessAuditEvent;
import com.enterprise.testagent.domain.supportaccess.SupportAccessAuditQuery;
import com.enterprise.testagent.domain.supportaccess.SupportAccessGrant;
import com.enterprise.testagent.domain.supportaccess.SupportAccessRepository;
import com.enterprise.testagent.domain.user.UserId;
import com.enterprise.testagent.persistence.mybatis.MyBatisSupportAccessRepository;
import com.enterprise.testagent.persistence.mybatis.SupportAccessMapper;
import java.time.Instant;
import java.util.UUID;
import org.apache.ibatis.session.SqlSessionFactory;
import org.flywaydb.core.Flyway;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.mybatis.spring.SqlSessionFactoryBean;
import org.mybatis.spring.SqlSessionTemplate;
import org.springframework.core.io.support.PathMatchingResourcePatternResolver;
import org.springframework.jdbc.core.simple.JdbcClient;
import org.springframework.jdbc.datasource.SingleConnectionDataSource;

/** 验证排查授权 migration、MyBatis XML 和一年保留清理。 */
class SupportAccessRepositoryIntegrationTest {

    private static final Instant ISSUED_AT = Instant.parse("2024-08-05T00:00:00Z");
    private static final UserId ACTOR_ID = new UserId("usr_support_persistence_actor");
    private static final UserId TARGET_ID = new UserId("usr_support_persistence_target");
    private SingleConnectionDataSource dataSource;
    private SupportAccessRepository repository;

    @BeforeEach
    void setUp() throws Exception {
        dataSource = new SingleConnectionDataSource(
                "jdbc:h2:mem:testagent_support_access_%s;MODE=PostgreSQL;DATABASE_TO_UPPER=false"
                        .formatted(UUID.randomUUID().toString().replace("-", "")),
                "sa", "", true);
        JdbcClient jdbc = JdbcClient.create(dataSource);
        // 以迁移前一版本为基线，只执行本功能 migration，避免 H2 被无关的 PostgreSQL 专用历史 SQL 阻断。
        jdbc.sql("""
                create table users (
                    id bigint generated by default as identity primary key,
                    user_id varchar(128) not null unique,
                    unified_auth_id varchar(128) not null unique,
                    username varchar(128) not null,
                    password_hash varchar(255) not null,
                    status varchar(32) not null,
                    created_at timestamp not null,
                    updated_at timestamp not null
                )
                """).update();
        Flyway.configure().dataSource(dataSource).locations("classpath:db/migration")
                .baselineOnMigrate(true)
                .baselineVersion("20260805131999")
                .target("20260805132000").load().migrate();
        jdbc.sql("""
                insert into users(user_id, unified_auth_id, username, password_hash, status, created_at, updated_at)
                values
                  ('usr_support_persistence_actor', 'auth_support_actor', 'support-actor', 'hash', 'ACTIVE', :now, :now),
                  ('usr_support_persistence_target', 'auth_support_target', 'support-target', 'hash', 'ACTIVE', :now, :now)
                """).param("now", ISSUED_AT).update();
        SqlSessionFactoryBean factory = new SqlSessionFactoryBean();
        factory.setDataSource(dataSource);
        factory.setMapperLocations(new PathMatchingResourcePatternResolver()
                .getResources("classpath*:mybatis/**/*.xml"));
        SqlSessionFactory sessionFactory = factory.getObject();
        SupportAccessMapper mapper = new SqlSessionTemplate(sessionFactory).getMapper(SupportAccessMapper.class);
        repository = new MyBatisSupportAccessRepository(mapper);
    }

    @AfterEach
    void tearDown() {
        dataSource.destroy();
    }

    @Test
    void savesQueriesRevokesAndPurgesSupportAccessAudit() {
        SupportAccessGrant grant = new SupportAccessGrant(
                "sag_persistence", ACTOR_ID, "support-actor", "INC-OLD", "历史问题排查",
                "1".repeat(64), ISSUED_AT, ISSUED_AT.plusSeconds(1800), null, null, "trace_support");
        repository.saveGrant(grant);
        repository.appendAuditEvent(new SupportAccessAuditEvent(
                "sae_persistence", grant.grantId(), ACTOR_ID.value(), "support-actor",
                TARGET_ID.value(), "support-target", grant.incidentId(), grant.reason(),
                "SESSION_LIST", "USER", TARGET_ID.value(), null, "SUCCESS", null,
                "trace_support", "127.0.0.1", "2".repeat(64), ISSUED_AT.plusSeconds(30)));

        assertThat(repository.findGrant(grant.grantId())).contains(grant);
        var page = repository.findAuditEvents(
                new SupportAccessAuditQuery(ACTOR_ID.value(), TARGET_ID.value(), "INC-OLD", "SUCCESS"),
                new PageRequest(1, 20));
        assertThat(page.total()).isEqualTo(1);
        assertThat(page.items().getFirst().pathDigest()).isNull();

        repository.revokeGrant(grant.grantId(), ISSUED_AT.plusSeconds(60), "TEST_REVOKE");
        assertThat(repository.findGrant(grant.grantId()))
                .get()
                .extracting(SupportAccessGrant::revokeReason)
                .isEqualTo("TEST_REVOKE");

        assertThat(repository.deleteExpiredBefore(Instant.parse("2025-08-05T00:00:00Z"))).isEqualTo(2);
        assertThat(repository.findGrant(grant.grantId())).isEmpty();
    }

    @Test
    void returnsLatestPersistedIncidentForActor() {
        repository.saveGrant(new SupportAccessGrant(
                "sag_persistence_old", ACTOR_ID, "support-actor", "INC-OLDER", "较早排查",
                "1".repeat(64), ISSUED_AT, ISSUED_AT.plusSeconds(1800), null, null, "trace_old"));
        repository.saveGrant(new SupportAccessGrant(
                "sag_persistence_latest", ACTOR_ID, "support-actor", "INC-LATEST", "最近排查",
                "2".repeat(64), ISSUED_AT.plusSeconds(60), ISSUED_AT.plusSeconds(1860), null, null, "trace_latest"));

        assertThat(repository.findLatestIncidentId(ACTOR_ID)).contains("INC-LATEST");
        assertThat(repository.findLatestIncidentId(new UserId("usr_without_grant"))).isEmpty();
    }
}
