package com.enterprise.testagent.persistence;

import static org.assertj.core.api.Assertions.assertThat;

import com.enterprise.testagent.domain.workspace.ExperienceWorkspaceBinding;
import com.enterprise.testagent.domain.workspace.ExperienceWorkspaceRepository;
import com.enterprise.testagent.domain.workspace.Workspace;
import com.enterprise.testagent.domain.workspace.WorkspaceId;
import com.enterprise.testagent.domain.workspace.WorkspaceStatus;
import com.enterprise.testagent.persistence.mybatis.ExperienceWorkspaceMapper;
import com.enterprise.testagent.persistence.mybatis.MyBatisExperienceWorkspaceRepository;
import com.enterprise.testagent.persistence.mybatis.MyBatisPersistenceConfig;
import java.time.Instant;
import java.util.Optional;
import java.util.UUID;
import org.apache.ibatis.session.SqlSessionFactory;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.mybatis.spring.SqlSessionTemplate;
import org.springframework.jdbc.core.simple.JdbcClient;
import org.springframework.jdbc.datasource.SingleConnectionDataSource;

/** 验证体验 Workspace 与服务器当前绑定全部通过 MyBatis XML 幂等写入。 */
class MyBatisExperienceWorkspaceRepositoryIntegrationTest {

    private static final Instant NOW = Instant.parse("2026-08-09T13:00:00Z");

    private SingleConnectionDataSource dataSource;
    private JdbcClient jdbcClient;
    private ExperienceWorkspaceRepository repository;

    @BeforeEach
    void setUp() throws Exception {
        dataSource = new SingleConnectionDataSource(
                "jdbc:h2:mem:testagent_experience_%s;MODE=PostgreSQL;DATABASE_TO_UPPER=false"
                        .formatted(UUID.randomUUID().toString().replace("-", "")),
                "sa",
                "",
                true);
        jdbcClient = JdbcClient.create(dataSource);
        jdbcClient.sql("""
                        create table workspaces (
                            id bigint generated by default as identity primary key,
                            workspace_id varchar(128) not null unique,
                            name varchar(255) not null,
                            root_path text not null,
                            status varchar(32) not null,
                            linux_server_id varchar(128),
                            trace_id varchar(128) not null,
                            created_at timestamp not null,
                            updated_at timestamp not null
                        )
                        """).update();
        jdbcClient.sql("""
                        create table experience_workspace_bindings (
                            linux_server_id varchar(128) primary key,
                            workspace_id varchar(128) not null unique,
                            configured_parameter_value text not null,
                            trace_id varchar(128) not null,
                            created_at timestamp not null,
                            updated_at timestamp not null,
                            constraint fk_experience_workspace_bindings_workspace
                                foreign key (workspace_id) references workspaces(workspace_id)
                        )
                        """).update();
        SqlSessionFactory factory = new MyBatisPersistenceConfig().sqlSessionFactory(dataSource);
        ExperienceWorkspaceMapper mapper = new SqlSessionTemplate(factory).getMapper(ExperienceWorkspaceMapper.class);
        repository = new MyBatisExperienceWorkspaceRepository(mapper);
    }

    @AfterEach
    void tearDown() {
        dataSource.destroy();
    }

    @Test
    void repeatedRegistrationIsIdempotentAndDirectoryChangeRetainsHistory() {
        Workspace first = workspace("wrk_exp_first", "/srv/experience-a", "trace_first", NOW);

        assertThat(repository.registerCurrentIfUnchanged(
                first, "${ROOT}/experience-a", "trace_first", Optional.empty())).isTrue();
        ExperienceWorkspaceBinding firstBinding = repository.findCurrentByLinuxServerId("server-a").orElseThrow();
        assertThat(repository.registerCurrentIfUnchanged(
                first, "${ROOT}/experience-a", "trace_repeat", Optional.of(firstBinding))).isTrue();

        assertThat(jdbcClient.sql("select count(*) from workspaces").query(Long.class).single()).isOne();
        assertThat(repository.findCurrentByLinuxServerId("server-a"))
                .get()
                .extracting(ExperienceWorkspaceBinding::workspaceId)
                .isEqualTo(first.workspaceId());

        Workspace second = workspace(
                "wrk_exp_second", "/srv/experience-b", "trace_second", NOW.plusSeconds(60));
        ExperienceWorkspaceBinding repeatedBinding = repository.findCurrentByLinuxServerId("server-a").orElseThrow();
        assertThat(repository.registerCurrentIfUnchanged(
                second, "${ROOT}/experience-b", "trace_second", Optional.of(repeatedBinding))).isTrue();

        assertThat(jdbcClient.sql("select count(*) from workspaces").query(Long.class).single()).isEqualTo(2L);
        assertThat(repository.findCurrentByLinuxServerId("server-a"))
                .get()
                .satisfies(binding -> {
                    assertThat(binding.workspaceId()).isEqualTo(second.workspaceId());
                    assertThat(binding.configuredParameterValue()).isEqualTo("${ROOT}/experience-b");
                    assertThat(binding.createdAt()).isEqualTo(NOW);
                    assertThat(binding.updatedAt()).isEqualTo(NOW.plusSeconds(60));
                });
        assertThat(jdbcClient.sql("select count(*) from workspaces where workspace_id = 'wrk_exp_first'")
                .query(Long.class).single()).isOne();
    }

    @Test
    void staleWriterCannotOverwriteNewerCurrentBinding() {
        Workspace first = workspace("wrk_exp_first", "/srv/experience-a", "trace_first", NOW);
        assertThat(repository.registerCurrentIfUnchanged(
                first, "${ROOT}/experience-a", "trace_first", Optional.empty())).isTrue();
        ExperienceWorkspaceBinding staleSnapshot = repository.findCurrentByLinuxServerId("server-a").orElseThrow();

        Workspace current = workspace("wrk_exp_current", "/srv/experience-b", "trace_current", NOW.plusSeconds(60));
        assertThat(repository.registerCurrentIfUnchanged(
                current, "${ROOT}/experience-b", "trace_current", Optional.of(staleSnapshot))).isTrue();
        Workspace late = workspace("wrk_exp_late", "/srv/experience-old", "trace_late", NOW.plusSeconds(120));

        assertThat(repository.registerCurrentIfUnchanged(
                late, "${ROOT}/experience-old", "trace_late", Optional.of(staleSnapshot))).isFalse();
        assertThat(repository.findCurrentByLinuxServerId("server-a"))
                .get()
                .extracting(ExperienceWorkspaceBinding::workspaceId)
                .isEqualTo(current.workspaceId());
    }

    private Workspace workspace(String workspaceId, String rootPath, String traceId, Instant time) {
        return new Workspace(
                new WorkspaceId(workspaceId),
                "体验工作区",
                rootPath,
                WorkspaceStatus.ACTIVE,
                time,
                time,
                "server-a",
                traceId);
    }
}
